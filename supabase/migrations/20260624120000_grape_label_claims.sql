-- Catalog security model:
-- This migration enables row-level security and creates read-only SELECT policies
-- for the authenticated role on the catalog tables below. Writes should use
-- service-role credentials (seeding/migrations/admin operations).

-- ============================================================
-- Catalog RLS (authenticated read-only)
-- ============================================================
do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'chemical_label_sources',
    'chemical_label_claims',
    'chemical_label_claim_mrls'
  ]
  loop
    execute format('alter table public.%I enable row level security', tbl);

    if not exists (
      select 1
      from pg_policies
      where schemaname = 'public'
        and tablename = tbl
        and policyname = 'Allow authenticated read access'
    ) then
      execute format(
        'create policy "Allow authenticated read access" on public.%I for select to authenticated using (true)',
        tbl
      );
    end if;
  end loop;
end $$;

do $$
begin
  if not exists (
    select 1 from pg_trigger where tgname = 'handle_chemical_label_sources_updated_at'
  ) then
    create trigger handle_chemical_label_sources_updated_at
      before update on public.chemical_label_sources
      for each row execute procedure extensions.moddatetime(updated_at);
  end if;

  if not exists (
    select 1 from pg_trigger where tgname = 'handle_chemical_label_claims_updated_at'
  ) then
    create trigger handle_chemical_label_claims_updated_at
      before update on public.chemical_label_claims
      for each row execute procedure extensions.moddatetime(updated_at);
  end if;
end $$;
